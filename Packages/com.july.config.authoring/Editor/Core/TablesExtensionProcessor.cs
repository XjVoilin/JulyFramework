using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace July.Config.Authoring
{
    public sealed class TablesExtensionProcessor : IConfigOutputProcessor
    {
        public void Process(ConfigOutputContext context)
        {
            var text = new StringBuilder("// <auto-generated/>\nusing System;\nusing System.Collections.Generic;\n");
            text.AppendLine("namespace " + context.Task.Namespace);
            text.AppendLine("{\n    public partial class Tables\n    {");
            text.Append("        public static readonly string[] TableNames = { ");
            for (var i = 0; i < context.Tables.Count; i++)
            {
                if (i > 0) text.Append(", ");
                text.Append('"').Append(context.Tables[i].LoadKey).Append('"');
            }
            text.AppendLine(" };\n        public void RegisterTo(Dictionary<Type, object> registry)\n        {");
            foreach (var table in context.Tables)
                text.AppendLine($"            registry[typeof({table.TypeName})] = {table.PropertyName};");
            text.AppendLine("        }\n    }\n}");
            context.WriteCode("TablesExt.cs", text.ToString());
        }

        internal static IReadOnlyList<ConfigTableInfo> ReadTables(string codeDirectory)
        {
            var file = Path.Combine(codeDirectory, "Tables.cs");
            var matches = Regex.Matches(File.ReadAllText(file),
                @"(?m)^\s*(\w+)\s*=\s*new\s+([\w.]+)\(loader\(""([^""]+)""\)\)");
            if (matches.Count == 0) throw new InvalidOperationException("No table loaders found in " + file);
            var tables = new List<ConfigTableInfo>(matches.Count);
            foreach (Match match in matches)
                tables.Add(new ConfigTableInfo(match.Groups[2].Value, match.Groups[1].Value, match.Groups[3].Value));
            return tables;
        }
    }
}
