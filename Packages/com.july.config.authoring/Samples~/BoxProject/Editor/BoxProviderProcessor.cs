using System;
using System.Linq;
using System.Text;

namespace July.Config.Authoring.Samples
{
    // Project-specific provider policy; opt-in example, not part of the default scheme.
    public sealed class BoxProviderProcessor : IConfigOutputProcessor
    {
        public void Process(ConfigOutputContext context)
        {
            var module = context.Task.Id;
            var topModule = context.Task.Namespace;
            var props = context.Tables;
            var gameIdStr = module.Replace("Game", "");
            if (!int.TryParse(gameIdStr, out var gameId)) throw new InvalidOperationException("Expected a GameNNN module: " + module);

            var langProp = props?.FirstOrDefault(p =>
                p.PropertyName == "TbLanguage" || p.PropertyName.EndsWith("Language") && p.PropertyName.StartsWith("Tb"));
            var hasLanguage = langProp?.PropertyName != null;
            var langPropName = hasLanguage ? langProp?.PropertyName : null;

            var uiWindowProp = props?.FirstOrDefault(p => p.TypeName.EndsWith("UIWindow"));
            var hasUIWindow = uiWindowProp?.TypeName != null;
            var uiWindowTbType = hasUIWindow ? $"{topModule}.{uiWindowProp?.TypeName}" : null;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            if (hasUIWindow) sb.AppendLine("using July.Arch;");
            sb.AppendLine("using July.Config;");
            sb.AppendLine("using July.Localization;");
            sb.AppendLine("using July.UI;");
            sb.AppendLine("using MiniGames;");
            sb.AppendLine("using Luban.SimpleJSON;");
            sb.AppendLine();
            sb.AppendLine($"namespace MiniGames.{module}");
            sb.AppendLine("{");
            sb.AppendLine($"    [MiniGameConfig({gameId})]");
            sb.AppendLine($"    public class {module}ConfigProvider : IMiniGameConfigProvider");
            sb.AppendLine("    {");
            sb.AppendLine($"        public string[] GetTableNames() => {topModule}.Tables.TableNames;");
            sb.AppendLine(
                $"        public object CreateTables(Func<string, JSONNode> loader) => new {topModule}.Tables(loader);");
            sb.AppendLine($"        public void RegisterTables(object tables, Dictionary<Type, object> registry)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var t = ({topModule}.Tables)tables;");
            sb.AppendLine($"            registry[typeof({topModule}.Tables)] = t;");
            sb.AppendLine("            t.RegisterTo(registry);");
            sb.AppendLine("        }");

            if (hasLanguage)
            {
                sb.AppendLine(
                    $"        public ILocalizationDataProvider CreateLocalizationProvider(object tables) => new {module}LocalizationProvider(({topModule}.Tables)tables);");
            }

            if (hasUIWindow)
            {
                sb.AppendLine(
                    $"        public IUIWindowProvider CreateUIWindowProvider() => new {module}UIWindowProvider();");
            }

            sb.AppendLine("    }");

            if (hasLanguage)
            {
                sb.AppendLine();
                sb.AppendLine($"    public class {module}LocalizationProvider : ILocalizationDataProvider");
                sb.AppendLine("    {");
                sb.AppendLine($"        private readonly {topModule}.Tables _tables;");
                sb.AppendLine($"        public {module}LocalizationProvider({topModule}.Tables tables) {{ _tables = tables; }}");
                sb.AppendLine("        public string DefaultLanguage => \"CN\";");
                sb.AppendLine("        public IReadOnlyList<string> SupportedLanguages { get; } = new[] { \"CN\" };");
                sb.AppendLine("        public Dictionary<string, string> LoadLanguage(string languageCode)");
                sb.AppendLine("        {");
                sb.AppendLine("            if (languageCode != \"CN\") return null;");
                sb.AppendLine($"            var dict = new Dictionary<string, string>(_tables.{langPropName}.DataList.Count);");
                sb.AppendLine($"            foreach (var e in _tables.{langPropName}.DataList)");
                sb.AppendLine("                dict[e.Id] = e.Text.Replace(\"\\\\n\", \"\\n\");");
                sb.AppendLine("            return dict;");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
            }

            if (hasUIWindow)
            {
                sb.AppendLine();
                sb.AppendLine($"    public sealed class {module}UIWindowProvider : IUIWindowProvider");
                sb.AppendLine("    {");
                sb.AppendLine("        public bool TryResolve(int windowId, out UIOpenOptions options)");
                sb.AppendLine("        {");
                sb.AppendLine("            var configSystem = ArchContext.Current.GetSystem<IConfigSystem>();");
                sb.AppendLine($"            if (configSystem == null || !configSystem.TryGetTable<{uiWindowTbType}>(out var table))");
                sb.AppendLine("            {");
                sb.AppendLine("                options = null;");
                sb.AppendLine("                return false;");
                sb.AppendLine("            }");
                sb.AppendLine();
                sb.AppendLine("            var row = table.GetOrDefault(windowId);");
                sb.AppendLine("            if (row == null)");
                sb.AppendLine("            {");
                sb.AppendLine("                options = null;");
                sb.AppendLine("                return false;");
                sb.AppendLine("            }");
                sb.AppendLine();
                sb.AppendLine("            options = new UIOpenOptions");
                sb.AppendLine("            {");
                sb.AppendLine("                WindowIdentifier = new WindowIdentifier(row.Id, row.WindowName),");
                sb.AppendLine("                Layer = (UILayer)row.UiLayer,");
                sb.AppendLine("                OpenAnimationType = (UIAnimationType)row.EnterAnimType,");
                sb.AppendLine("                CloseAnimationType = (UIAnimationType)row.ExitAnimType,");
                sb.AppendLine("                ShowMask = row.IsNeedBlackMask,");
                sb.AppendLine("                ClickMaskToClose = row.IsClickBlankQuit,");
                sb.AppendLine("                IgnoreSafeArea = row.IsIgnoreSafeArea,");
                sb.AppendLine("                QueueMode = (UIQueueMode)row.QueueMode,");
                sb.AppendLine("            };");
                sb.AppendLine("            return true;");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
            }

            sb.AppendLine("}");

            context.WriteCode($"{module}ConfigProvider.cs", sb.ToString());
        }

    }
}
